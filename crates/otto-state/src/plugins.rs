//! Runtime-plugins registry (migration 0062).
//!
//! Stores installed out-of-process plugins. The supervisor reads `list_enabled`
//! at boot/refresh to spawn sidecars; the reverse proxy + management API read/write
//! here; the host API authenticates a sidecar via [`PluginsRepo::find_enabled_by_token`].

use crate::DbPool;
use chrono::Utc;
use serde::Serialize;
use sha2::{Digest, Sha256};
use sqlx::Row;

use otto_core::{Error, Result};

/// Prefix marking a SHA-256-hashed plugin token stored in `plugins.token`.
const TOKEN_HASH_PREFIX: &str = "sha256:";

/// Hash a raw plugin token for persistence/lookup so plaintext plugin
/// credentials never sit in `otto.db` or pre-migration backups.
pub fn hash_plugin_token(raw: &str) -> String {
    let mut h = Sha256::new();
    h.update(raw.as_bytes());
    format!("{TOKEN_HASH_PREFIX}{}", hex::encode(h.finalize()))
}

/// An installed runtime plugin. `token` is never serialized to clients.
#[derive(Debug, Clone, Serialize)]
pub struct PluginRecord {
    pub slug: String,
    pub name: String,
    pub icon: String,
    pub version: String,
    pub description: String,
    pub source: String,
    pub exec: Vec<String>,
    pub ui_dir: Option<String>,
    pub health: String,
    pub enabled: bool,
    #[serde(skip_serializing)]
    pub token: String,
    pub installed_at: String,
}

/// Fields needed to install/replace a plugin (token generated by the caller).
pub struct NewPlugin {
    pub slug: String,
    pub name: String,
    pub icon: String,
    pub version: String,
    pub description: String,
    pub source: String,
    pub exec: Vec<String>,
    pub ui_dir: Option<String>,
    pub health: String,
    pub token: String,
}

#[derive(Clone)]
pub struct PluginsRepo {
    pool: DbPool,
}

fn row_to_record(r: &sqlx::sqlite::SqliteRow) -> Result<PluginRecord> {
    let exec_json: String = r.get("exec_json");
    let exec: Vec<String> = serde_json::from_str(&exec_json)
        .map_err(|e| Error::Internal(format!("plugin exec_json parse: {e}")))?;
    Ok(PluginRecord {
        slug: r.get("slug"),
        name: r.get("name"),
        icon: r.get("icon"),
        version: r.get("version"),
        description: r.get("description"),
        source: r.get("source"),
        exec,
        ui_dir: r.get("ui_dir"),
        health: r.get("health"),
        enabled: r.get::<i64, _>("enabled") != 0,
        token: r.get("token"),
        installed_at: r.get("installed_at"),
    })
}

const COLS: &str =
    "slug, name, icon, version, description, source, exec_json, ui_dir, health, enabled, token, installed_at";

impl PluginsRepo {
    pub fn new(pool: impl Into<DbPool>) -> Self {
        let pool: DbPool = pool.into();
        Self { pool }
    }

    /// Install or replace a plugin (preserves nothing; enabled defaults to off).
    /// Only the SHA-256 hash of `p.token` is persisted in SQLite.
    pub async fn upsert(&self, p: NewPlugin) -> Result<PluginRecord> {
        let exec_json = serde_json::to_string(&p.exec)
            .map_err(|e| Error::Internal(format!("plugin exec encode: {e}")))?;
        let token_hash = hash_plugin_token(&p.token);
        let now = Utc::now().to_rfc3339();
        sqlx::query(
            "INSERT INTO plugins (slug, name, icon, version, description, source, exec_json, ui_dir, health, enabled, token, installed_at)
             VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, 0, ?, ?)
             ON CONFLICT(slug) DO UPDATE SET
               name=excluded.name, icon=excluded.icon, version=excluded.version,
               description=excluded.description, source=excluded.source, exec_json=excluded.exec_json,
               ui_dir=excluded.ui_dir, health=excluded.health, token=excluded.token, enabled=0",
        )
        .bind(&p.slug).bind(&p.name).bind(&p.icon).bind(&p.version).bind(&p.description)
        .bind(&p.source).bind(&exec_json).bind(&p.ui_dir).bind(&p.health).bind(&token_hash).bind(&now)
        .execute(&self.pool)
        .await
        .map_err(|e| Error::Internal(format!("plugin upsert: {e}")))?;
        self.get(&p.slug)
            .await?
            .ok_or_else(|| Error::Internal("plugin vanished after upsert".into()))
    }

    pub async fn get(&self, slug: &str) -> Result<Option<PluginRecord>> {
        let row = sqlx::query(sqlx::AssertSqlSafe(format!(
            "SELECT {COLS} FROM plugins WHERE slug = ?"
        )))
        .bind(slug)
        .fetch_optional(&self.pool)
        .await
        .map_err(|e| Error::Internal(format!("plugin get: {e}")))?;
        row.as_ref().map(row_to_record).transpose()
    }

    pub async fn list(&self) -> Result<Vec<PluginRecord>> {
        let rows = sqlx::query(sqlx::AssertSqlSafe(format!(
            "SELECT {COLS} FROM plugins ORDER BY name"
        )))
        .fetch_all(&self.pool)
        .await
        .map_err(|e| Error::Internal(format!("plugin list: {e}")))?;
        rows.iter().map(row_to_record).collect()
    }

    pub async fn list_enabled(&self) -> Result<Vec<PluginRecord>> {
        Ok(self
            .list()
            .await?
            .into_iter()
            .filter(|p| p.enabled)
            .collect())
    }

    /// Installed slugs (for the capabilities map).
    pub async fn list_slugs(&self) -> Result<Vec<String>> {
        let rows = sqlx::query("SELECT slug FROM plugins ORDER BY slug")
            .fetch_all(&self.pool)
            .await
            .map_err(|e| Error::Internal(format!("plugin slugs: {e}")))?;
        Ok(rows.iter().map(|r| r.get::<String, _>("slug")).collect())
    }

    pub async fn set_enabled(&self, slug: &str, enabled: bool) -> Result<()> {
        sqlx::query("UPDATE plugins SET enabled = ? WHERE slug = ?")
            .bind(enabled as i64)
            .bind(slug)
            .execute(&self.pool)
            .await
            .map_err(|e| Error::Internal(format!("plugin set_enabled: {e}")))?;
        Ok(())
    }

    pub async fn delete(&self, slug: &str) -> Result<()> {
        sqlx::query("DELETE FROM plugins WHERE slug = ?")
            .bind(slug)
            .execute(&self.pool)
            .await
            .map_err(|e| Error::Internal(format!("plugin delete: {e}")))?;
        Ok(())
    }

    /// Resolve an enabled plugin by its host-API token (sidecar authentication).
    pub async fn find_enabled_by_token(&self, token: &str) -> Result<Option<PluginRecord>> {
        let token_hash = hash_plugin_token(token);
        let row = sqlx::query(sqlx::AssertSqlSafe(format!(
            "SELECT {COLS} FROM plugins WHERE token = ? AND enabled = 1"
        )))
        .bind(&token_hash)
        .fetch_optional(&self.pool)
        .await
        .map_err(|e| Error::Internal(format!("plugin by token: {e}")))?;
        row.as_ref().map(row_to_record).transpose()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[tokio::test]
    async fn plugin_tokens_are_hashed_at_rest_and_matched_by_raw_token() {
        let pool = sqlx::sqlite::SqlitePoolOptions::new()
            .max_connections(1)
            .connect("sqlite::memory:")
            .await
            .unwrap();
        sqlx::migrate!("./migrations").run(&pool).await.unwrap();
        let repo = PluginsRepo::new(pool.clone());

        let raw = "raw-plugin-secret-token";
        let rec = repo
            .upsert(NewPlugin {
                slug: "demo".into(),
                name: "Demo".into(),
                icon: "box".into(),
                version: "1.0.0".into(),
                description: String::new(),
                source: "/tmp/demo".into(),
                exec: vec!["/bin/true".into()],
                ui_dir: None,
                health: "/health".into(),
                token: raw.into(),
            })
            .await
            .unwrap();
        // Plaintext token must never be stored in SQLite.
        assert_ne!(rec.token, raw);
        assert!(rec.token.starts_with(TOKEN_HASH_PREFIX));
        let stored: String = sqlx::query_scalar("SELECT token FROM plugins WHERE slug = 'demo'")
            .fetch_one(&pool)
            .await
            .unwrap();
        assert_ne!(stored, raw);
        assert_eq!(stored, hash_plugin_token(raw));

        // Disabled plugin must not authenticate.
        assert!(repo.find_enabled_by_token(raw).await.unwrap().is_none());

        repo.set_enabled("demo", true).await.unwrap();
        // Raw token authenticates; presenting the stored hash string does not.
        let found = repo
            .find_enabled_by_token(raw)
            .await
            .unwrap()
            .expect("enabled plugin resolves by raw token");
        assert_eq!(found.slug, "demo");
        assert!(repo.find_enabled_by_token(&stored).await.unwrap().is_none());
    }
}
