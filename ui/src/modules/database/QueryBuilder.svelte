    paletteW = PALETTE_W_DEFAULT;
    persistPaletteW();
  }

  // Canvas scroll container (cards + edges live in its content coordinates).
  let canvasEl = $state<HTMLDivElement | null>(null);
  // Per-card body scroll/height, so edge anchors follow a scrolled column list.
  let bodyScroll = $state<Map<string, number>>(new Map());
  let bodyHeight = $state<Map<string, number>>(new Map());
  function cardBody(node: HTMLElement, uid: string) {
    const sync = (): void => {
      bodyScroll = new Map(bodyScroll).set(uid, node.scrollTop);
      bodyHeight = new Map(bodyHeight).set(uid, node.clientHeight);
    };
    sync();
    node.addEventListener('scroll', sync, { passive: true });
    const ro = new ResizeObserver(sync);
    ro.observe(node);
    return {
      destroy() {
        node.removeEventListener('scroll', sync);
        ro.disconnect();
      },
    };
  }

  let dragUid = $state<string | null>(null);
  let dragOffX = 0;
  let dragOffY = 0;
  let pending = $state<{ fromUid: string; fromCol: string; side: 'l' | 'r' } | null>(null);
  let pendingPt = $state<{ x: number; y: number } | null>(null);
  let editEdge = $state<string | null>(null);

  // ── Per-connection persistence ─────────────────────────────────────────────
  const connKey = $derived(JSON.stringify([auth.me?.id, database.selectedConnId, database.accessRevision]));
  let restoredFor = $state<string | null>(null);
  $effect(() => {
    const key = connKey;
    if (restoredFor === key) return;
    restoredFor = key;
    const snap = builderCache.get(key);
    tables = snap?.tables ?? [];
    edges = snap?.edges ?? [];
    clauses = snap?.clauses ?? emptyClauses();
    selectedDb = snap?.selectedDb ?? '';
    if (snap?.canvasH) canvasH = snap.canvasH;
    importError = null;
  });
  $effect(() => {
    if (restoredFor !== connKey) return; // mid-switch: don't cross-save
    builderCache.set(connKey, { tables, edges, clauses, selectedDb, canvasH });
  });

  // ── Palette ─────────────────────────────────────────────────────────────────
  $effect(() => {
    void database.selectedConnId;
    void database.schemaRoot;
    void loadDatabases();
  });
  async function loadDatabases(): Promise<void> {
    if (!database.supportsBuilder) return;
    const dbs = await database.listBuilderDatabases();
    databases = dbs;
    if (dbs.length && !dbs.some((d) => d.path === selectedDb)) {
      selectedDb = (dbs.find((d) => d.name === database.activeDb) ?? dbs[0]).path;
    }
    await loadPaletteTables();
  }
  async function loadPaletteTables(): Promise<void> {
    paletteLoading = true;
    try {
      paletteTables = await database.listBuilderTables(selectedDb);
    } finally {
      paletteLoading = false;
    }
  }
  const filteredPalette = $derived.by(() => {
    const q = paletteSearch.trim().toLowerCase();
    return q ? paletteTables.filter((t) => t.label.toLowerCase().includes(q)) : paletteTables;
  });
  function dbName(path: string): string {
    return databases.find((d) => d.path === path)?.name ?? '';
  }
  const onCanvas = $derived(new Set(tables.map((t) => t.path)));

  // ── Cards ───────────────────────────────────────────────────────────────────
  function cardFrom(
    detail: ObjectDetail | null,
    base: Pick<CardTable, 'uid' | 'db' | 'table' | 'alias' | 'path' | 'x' | 'y'>,
  ): CardTable {
    return {
      ...base,
      columns: detail ? detail.columns.map((c) => ({ name: c.name, type: c.data_type })) : null,
      pk: detail?.primary_key ?? [],
      fks: (detail?.foreign_keys ?? []).map((f) => ({ columns: f.columns, ref_table: f.ref_table, ref_columns: f.ref_columns })),
    };
  }
  function nextSlot(n: number): { x: number; y: number } {
    const sx = canvasEl?.scrollLeft ?? 0;
    const sy = canvasEl?.scrollTop ?? 0;
    return { x: 24 + (n % 4) * (CARD_W + 56) + sx, y: 20 + Math.floor(n / 4) * 40 + (n % 4) * 18 + sy };
  }
  async function addTable(t: { label: string; path: string }): Promise<void> {
    const taken = new Set(tables.map((x) => x.alias));
    const alias = uniqueAlias(t.label, taken);
    const uid = nid('tbl');
    const first = tables.length === 0;
    const slot = nextSlot(tables.length);
    tables = [...tables, cardFrom(null, { uid, db: dbName(selectedDb), table: t.label, alias, path: t.path, ...slot })];
    importError = null;
    const detail = await database.fetchObject(t.path);
    tables = tables.map((c) => (c.uid === uid ? cardFrom(detail, c) : c));
    // A table dropped onto an empty builder is a "look at this table" — start
    // from all of its rows; joined tables start with nothing selected.
    if (first) clauses.select = [];
    // Offer FK joins automatically only when exactly one suggestion exists
    // for the new card: unambiguous and what the user nearly always wants.
    const mine = fkSuggestions(tables, edges).filter((s) => s.fromUid === uid || s.toUid === uid);
    if (!first && mine.length === 1) applySuggestion(mine[0]);
  }
  function removeTable(uid: string): void {
    const gone = tables.find((t) => t.uid === uid);
    tables = tables.filter((t) => t.uid !== uid);
    edges = edges.filter((e) => e.fromUid !== uid && e.toUid !== uid);
    if (gone) clauses = dropAlias(clauses, gone.alias);
  }
  function setAlias(uid: string, raw: string): void {
    const clean = raw.replace(/[^A-Za-z0-9_]/g, '_');
    const old = tables.find((t) => t.uid === uid)?.alias;
    if (old === undefined || old === clean || !clean) return;
    if (tables.some((t) => t.alias === clean)) {
      toasts.warn('Alias already used', `Another table on the canvas is already “${clean}”.`);
      return;
    }
    tables = tables.map((t) => (t.uid === uid ? { ...t, alias: clean } : t));
    clauses = renameAlias(clauses, old, clean);
  }
  function clearCanvas(): void {
    tables = [];
    edges = [];
    clauses = emptyClauses();
    importError = null;
  }

  // ── Columns on cards ↔ SELECT items ─────────────────────────────────────────
  const refKey = (r: ColRef): string => `${r.alias}.${r.column}`;
  function parseKey(k: string): ColRef {
    const i = k.indexOf('.');
    return { alias: k.slice(0, i), column: k.slice(i + 1) };
  }
  function isSelected(alias: string, column: string): boolean {
    return clauses.select.some((s) => s.kind === 'column' && s.ref.alias === alias && s.ref.column === column);
  }
  function toggleCol(alias: string, column: string): void {
    if (isSelected(alias, column)) {
      clauses.select = clauses.select.filter(
        (s) => !(s.kind === 'column' && s.ref.alias === alias && s.ref.column === column),
      );
    } else {
      clauses.select = [...clauses.select, { kind: 'column', id: nid('s'), ref: { alias, column } }];
    }
  }
  function selectAllOf(t: CardTable, on: boolean): void {
    const rest = clauses.select.filter((s) => !(s.kind === 'column' && s.ref.alias === t.alias));
    clauses.select = on
      ? [...rest, ...(t.columns ?? []).map((c): SelectItem => ({ kind: 'column', id: nid('s'), ref: { alias: t.alias, column: c.name } }))]
      : rest;
  }

  // Every column on the canvas, for the clause pickers.
  const colOptions = $derived(
    tables.flatMap((t) =>
      (t.columns ?? []).map((c) => ({ key: `${t.alias}.${c.name}`, alias: t.alias, column: c.name, type: c.type })),
    ),
  );
  const typeByKey = $derived(new Map(colOptions.map((o) => [o.key, o.type])));
  const kindOf = (r: ColRef): ReturnType<typeof valueKind> => valueKind(typeByKey.get(refKey(r)));
  const firstRef = (): ColRef | null => (colOptions[0] ? { alias: colOptions[0].alias, column: colOptions[0].column } : null);

  // ── SELECT list ─────────────────────────────────────────────────────────────
  function addColumnItem(): void {
    const r = firstRef();
    if (r) clauses.select = [...clauses.select, { kind: 'column', id: nid('s'), ref: r }];
  }
  function addAggregate(): void {
    clauses.select = [...clauses.select, { kind: 'aggregate', id: nid('s'), fn: 'COUNT', ref: null, as: 'count' }];
    autoGroup();
  }
  function addExpression(): void {
    clauses.select = [...clauses.select, { kind: 'expr', id: nid('s'), sql: '', as: '' }];
  }
  function moveSelect(i: number, d: number): void {
    const j = i + d;
    if (j < 0 || j >= clauses.select.length) return;
    const next = clauses.select.slice();
    [next[i], next[j]] = [next[j], next[i]];
    clauses.select = next;
  }
  function removeSelect(id: string): void {
    clauses.select = clauses.select.filter((s) => s.id !== id);
    clauses.orderBy = clauses.orderBy.filter((o) => !(o.target.kind === 'select' && o.target.id === id));
  }
  function setAggFn(it: Extract<SelectItem, { kind: 'aggregate' }>, fn: AggFn): void {
    const wasDefault = !it.as || it.as === defaultAggAlias(it.fn, it.ref);
    it.fn = fn;
    if (fn !== 'COUNT' && !it.ref) {
      const r = colOptions.find((o) => valueKind(o.type) === 'number') ?? colOptions[0];
      if (r) it.ref = { alias: r.alias, column: r.column };
    }
    if (wasDefault) it.as = defaultAggAlias(fn, it.ref);
  }
  function setAggArg(it: Extract<SelectItem, { kind: 'aggregate' }>, key: string): void {
    const wasDefault = !it.as || it.as === defaultAggAlias(it.fn, it.ref);
    it.ref = key === '*' ? null : parseKey(key);
    if (wasDefault) it.as = defaultAggAlias(it.fn, it.ref);
  }
  /** First aggregate on a query with plain columns and no GROUP BY yet: group
   *  by those columns (the SQL would be rejected otherwise). Visible, editable. */
  function autoGroup(): void {
    if (clauses.groupBy.length) return;
    const q = toQuery(dialect ?? 'mysql', tables, edges, clauses);
    clauses.groupBy = suggestGroupBy(q);
  }

  // ── Conditions (WHERE / HAVING) ─────────────────────────────────────────────
  function newCond(having: boolean): Condition | null {
    const r = firstRef();
    if (!r) return null;
    if (having) return { kind: 'cond', id: nid('c'), target: { ref: { ...r, column: '*' }, fn: 'COUNT' }, op: '>', value: '' };
    return { kind: 'cond', id: nid('c'), target: { ref: r }, op: opsFor(kindOf(r))[0], value: '' };
  }
  function addCond(g: CondGroup, having: boolean): void {
    const c = newCond(having);
    if (c) g.items.push(c);
  }
  function addGroup(g: CondGroup, having: boolean): void {
    const inner = emptyGroup(g.conj === 'AND' ? 'OR' : 'AND');
    const c = newCond(having);
    if (c) inner.items.push(c);
    g.items.push(inner);
  }
  function removeAt(g: CondGroup, i: number): void {
    g.items.splice(i, 1);
  }
  function condKind(c: Condition): ReturnType<typeof valueKind> {
    if (c.target.fn && c.target.fn !== 'MIN' && c.target.fn !== 'MAX') return 'number';
    return kindOf(c.target.ref);
  }
  function setCondCol(c: Condition, key: string): void {
    c.target = { ...c.target, ref: key === '*' ? { alias: c.target.ref.alias, column: '*' } : parseKey(key) };
    const allowed = opsFor(condKind(c));
    if (!allowed.includes(c.op)) c.op = allowed[0];
  }
  /** HAVING aggregate change: only COUNT takes `*`; others need a column. */
  function setHavingFn(c: Condition, fn: AggFn): void {
    let ref = c.target.ref;
    if (fn !== 'COUNT' && ref.column === '*') {
      const r = colOptions.find((o) => valueKind(o.type) === 'number') ?? colOptions[0];
      if (r) ref = { alias: r.alias, column: r.column };
    }
    c.target = { ref, fn };
  }
  function setListText(c: Condition, text: string): void {
    c.value = text;
    c.values = splitList(text);
  }
  const placeholderFor = (k: ReturnType<typeof valueKind>): string =>
    k === 'number' ? '0' : k === 'time' ? '2026-01-01' : k === 'bool' ? 'true' : 'value';
  function countConds(g: CondGroup): number {
    return g.items.reduce((n, it) => n + (it.kind === 'group' ? countConds(it) : 1), 0);
  }

  // ── GROUP BY / ORDER BY ─────────────────────────────────────────────────────
  function addGroupBy(key: string): void {
    if (!key || clauses.groupBy.some((r) => refKey(r) === key)) return;
    clauses.groupBy = [...clauses.groupBy, parseKey(key)];
  }
  function removeGroupBy(i: number): void {
    clauses.groupBy = clauses.groupBy.filter((_, j) => j !== i);
  }
  function orderKey(o: OrderItem): string {
    return o.target.kind === 'select' ? `sel:${o.target.id}` : `col:${refKey(o.target.ref)}`;
  }
  function setOrderTarget(o: OrderItem, key: string): void {
    o.target = key.startsWith('sel:') ? { kind: 'select', id: key.slice(4) } : { kind: 'column', ref: parseKey(key.slice(4)) };
  }
  function addOrder(): void {
    const agg = clauses.select.find((s) => s.kind === 'aggregate');
    const r = firstRef();
    const target: OrderItem['target'] | null = agg ? { kind: 'select', id: agg.id } : r ? { kind: 'column', ref: r } : null;
    if (target) clauses.orderBy = [...clauses.orderBy, { id: nid('o'), target, dir: agg ? 'DESC' : 'ASC', nulls: 'default' }];
  }
  function moveOrder(i: number, d: number): void {
    const j = i + d;
    if (j < 0 || j >= clauses.orderBy.length) return;
    const next = clauses.orderBy.slice();
    [next[i], next[j]] = [next[j], next[i]];
    clauses.orderBy = next;
  }
  function selectLabel(s: SelectItem): string {
    if (s.as?.trim()) return s.as.trim();
    if (s.kind === 'column') return refKey(s.ref);
    if (s.kind === 'aggregate') return `${s.fn}(${s.ref ? refKey(s.ref) : '*'})`;
    return s.sql.trim() || 'expression';
  }

  // ── Edges (drawing joins) ───────────────────────────────────────────────────
  function canvasPoint(ev: { clientX: number; clientY: number }): { x: number; y: number } {
    const rect = canvasEl?.getBoundingClientRect();
    if (!rect || !canvasEl) return { x: 0, y: 0 };
    return { x: ev.clientX - rect.left + canvasEl.scrollLeft, y: ev.clientY - rect.top + canvasEl.scrollTop };
  }
  function startDrag(ev: PointerEvent, uid: string): void {
    if (ev.button !== 0) return;
    const t = tables.find((x) => x.uid === uid);
    if (!t) return;
    const pt = canvasPoint(ev);
    dragUid = uid;
    dragOffX = pt.x - t.x;
    dragOffY = pt.y - t.y;
    (ev.currentTarget as HTMLElement).setPointerCapture?.(ev.pointerId);
    ev.preventDefault();
  }
  function startConnect(ev: PointerEvent, uid: string, col: string, side: 'l' | 'r'): void {
    if (ev.button !== 0) return;
    pending = { fromUid: uid, fromCol: col, side };
    pendingPt = canvasPoint(ev);
    canvasEl?.setPointerCapture?.(ev.pointerId);
    ev.stopPropagation();
    ev.preventDefault();
  }
  function commitConnect(uid: string, col: string): void {
    const p = pending;
    if (!p || (p.fromUid === uid && p.fromCol === col) || p.fromUid === uid) return;
    const dup = edges.some(
      (e) =>
        (e.fromUid === p.fromUid && e.fromCol === p.fromCol && e.toUid === uid && e.toCol === col) ||
        (e.fromUid === uid && e.fromCol === col && e.toUid === p.fromUid && e.toCol === p.fromCol),
    );
    if (dup) return;
    edges = [...edges, { id: nid('edge'), fromUid: p.fromUid, fromCol: p.fromCol, toUid: uid, toCol: col, type: 'INNER' }];
  }
  function onCanvasMove(ev: PointerEvent): void {
    if (dragUid) {
      const pt = canvasPoint(ev);
      const nx = Math.max(0, pt.x - dragOffX);
      const ny = Math.max(0, pt.y - dragOffY);
      tables = tables.map((t) => (t.uid === dragUid ? { ...t, x: nx, y: ny } : t));
    } else if (pending) pendingPt = canvasPoint(ev);
  }
  function onCanvasUp(ev: PointerEvent): void {
    dragUid = null;
    if (pending) {
      const el = document.elementFromPoint(ev.clientX, ev.clientY) as HTMLElement | null;
      const target = el?.closest<HTMLElement>('.handle, .col-row');
      const uid = target?.dataset.uid;
      const col = target?.dataset.col;
      if (uid && col) commitConnect(uid, col);
    }
    pending = null;
    pendingPt = null;
  }
  function colIndex(t: CardTable, col: string): number {
    return Math.max(0, (t.columns ?? []).findIndex((c) => c.name === col));
  }
  function visibleBodyH(t: CardTable): number {
    const measured = bodyHeight.get(t.uid);
    if (measured && measured > 0) return measured;
    return Math.min(BODY_MAX_H, (t.columns?.length ?? 1) * ROW_H + BODY_PAD * 2);
  }
  function handleY(t: CardTable, col: string): number {
    const bodyTop = t.y + HEADER_H;
    const y = bodyTop + BODY_PAD + colIndex(t, col) * ROW_H + ROW_H / 2 - (bodyScroll.get(t.uid) ?? 0);
    return Math.min(bodyTop + Math.max(2, visibleBodyH(t) - 2), Math.max(bodyTop + 2, y));
  }
  function isClamped(t: CardTable, col: string): boolean {
