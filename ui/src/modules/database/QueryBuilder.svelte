  const CANVAS_H_KEY = 'db.qbCanvasH';
  let canvasH = $state<number | null>(loadCanvasH());
  function loadCanvasH(): number | null {
    try {
      const v = Number(localStorage.getItem(CANVAS_H_KEY));
      return Number.isFinite(v) && v >= 140 ? v : null;
    } catch {
      return null;
