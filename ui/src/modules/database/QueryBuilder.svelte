  function bezier(x1: number, y1: number, s1: 'l' | 'r', x2: number, y2: number, s2: 'l' | 'r'): string {
    const k = Math.max(40, Math.abs(x2 - x1) / 2);
    const c1x = s1 === 'r' ? x1 + k : x1 - k;
    const c2x = s2 === 'r' ? x2 + k : x2 - k;
