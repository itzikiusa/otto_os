const SHORTCODE_RE = /(?<![/\w]):([+-]?[a-z0-9_+-]{1,32}):(?![/\w])/gi;

export function resolveEmojiShortcode(name: string): string | null {
  return EMOJI_SHORTCODES[name.toLowerCase()] ?? null;
}

/** Expand known `:shortcode:` tokens in plain prose while leaving unknown `:foo:`,
 *  URLs (`https://...`), and path/port strings untouched. */
export function replaceEmojiShortcodes(text: string): string {
  if (!text || !text.includes(':')) return text;
  return text.replace(SHORTCODE_RE, (full, rawName: string) => {
    return resolveEmojiShortcode(rawName) ?? full;
  });
}

export interface EmojiSuggestion {
  shortcode: string;
  emoji: string;
}

const ALL_ENTRIES: readonly EmojiSuggestion[] = Object.entries(EMOJI_SHORTCODES).map(
  ([shortcode, emoji]) => ({ shortcode, emoji }),
);

export function searchEmojiShortcodes(query: string, limit = 8): EmojiSuggestion[] {
  const q = query.trim().toLowerCase().replace(/^:+|:+$/g, '');
  if (!q) return ALL_ENTRIES.slice(0, limit);
  const prefixHits: EmojiSuggestion[] = [];
  const substrHits: EmojiSuggestion[] = [];
  const seenEmojis = new Set<string>();
  for (let i = 0; i < ALL_ENTRIES.length; i++) {
    const entry = ALL_ENTRIES[i];
    if (entry.shortcode.startsWith(q)) {
      if (!seenEmojis.has(entry.emoji)) {
        seenEmojis.add(entry.emoji);
        prefixHits.push(entry);
        if (prefixHits.length >= limit) return prefixHits;
      }
    } else if (entry.shortcode.includes(q)) {
      substrHits.push(entry);
    }
  }
  for (let i = 0; i < substrHits.length && prefixHits.length < limit; i++) {
    const entry = substrHits[i];
    if (!seenEmojis.has(entry.emoji)) {
      seenEmojis.add(entry.emoji);
      prefixHits.push(entry);
    }
  }
  return prefixHits;
}
