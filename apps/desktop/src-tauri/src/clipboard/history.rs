//! Clipboard history — the pure part: entries, de-duplication, retention,
//! search, and what is never recorded. No AppKit and no IO, so all of it is
//! unit-tested here.

use serde::{Deserialize, Serialize};

pub const MAX_ENTRIES: usize = 500;
pub const MAX_AGE_MS: u64 = 30 * 24 * 60 * 60 * 1000;
/// Total bytes of unpinned images kept; the oldest go first.
pub const MAX_IMAGE_BYTES_TOTAL: u64 = 512 << 20;
/// A single copy bigger than this is skipped, not truncated.
pub const MAX_TEXT_BYTES: usize = 256 << 10;
pub const MAX_IMAGE_BYTES: usize = 25 << 20;

/// A pasteboard carrying any of these types is never read: the
/// nspasteboard.org markers (password managers, generated or transient
/// content) and the password managers' own types.
pub const SKIP_TYPES: &[&str] = &[
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword",
    "de.petermaurer.TransientPasteboardType",
    "com.typeit4me.clipping",
    "Pasteboard generator type",
    "net.antelle.keeweb",
];

pub fn skip(types: &[String]) -> bool {
    types.iter().any(|t| SKIP_TYPES.contains(&t.as_str()))
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Kind {
    Text,
    Link,
    File,
    Image,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct Source {
    pub name: String,
    pub bundle_id: Option<String>,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct Entry {
    /// Content hash: the same content copied again is the same entry.
    pub id: String,
    pub kind: Kind,
    /// The text or link; file paths one per line; empty for an image (its
    /// bytes live in `images/<id>.png`).
    #[serde(default)]
    pub text: String,
    #[serde(default)]
    pub width: u32,
    #[serde(default)]
    pub height: u32,
    pub size: u64,
    pub source: Option<Source>,
    pub first_ms: u64,
    pub last_ms: u64,
    pub count: u32,
    #[serde(default)]
    pub pinned: bool,
}

/// FNV-1a 64 over the kind and the content — stable across builds (it is
/// persisted), and 500 entries make a collision a non-event.
pub fn content_id(kind: Kind, bytes: &[u8]) -> String {
    let mut h: u64 = 0xcbf2_9ce4_8422_2325;
    for &b in [kind as u8].iter().chain(bytes) {
        h = (h ^ u64::from(b)).wrapping_mul(0x0000_0100_0000_01b3);
    }
    format!("{h:016x}")
}

/// A copied string is a link when it is one http(s) URL and nothing else.
pub fn text_kind(s: &str) -> Kind {
    let t = s.trim();
    let url = t.starts_with("https://") || t.starts_with("http://");
    if url && !t.contains(char::is_whitespace) {
        Kind::Link
    } else {
        Kind::Text
    }
}

/// Add a copy. Content already in the history moves to the top with its
/// counter bumped (its first source and first-copied time stay); returns
/// true when it was new.
pub fn record(entries: &mut Vec<Entry>, new: Entry) -> bool {
    match entries.iter().position(|e| e.id == new.id) {
        Some(i) => {
            let mut e = entries.remove(i);
            e.last_ms = new.last_ms;
            e.count = e.count.saturating_add(1);
            entries.insert(0, e);
            false
        }
        None => {
            entries.insert(0, new);
            true
        }
    }
}

/// Apply retention (newest first): unpinned entries older than 30 days, past
/// the newest 500, or past the image-bytes budget go. Pinned ones always
/// stay. Returns what was dropped (the caller deletes their image files).
pub fn prune(entries: &mut Vec<Entry>, now: u64) -> Vec<Entry> {
    let (mut kept, mut image_bytes) = (0usize, 0u64);
    let (keep, dropped): (Vec<Entry>, Vec<Entry>) = entries.drain(..).partition(|e| {
        if e.pinned {
            return true;
        }
        let image = if e.kind == Kind::Image { e.size } else { 0 };
        let ok = now.saturating_sub(e.last_ms) <= MAX_AGE_MS
            && kept < MAX_ENTRIES
            && image_bytes + image <= MAX_IMAGE_BYTES_TOTAL;
        if ok {
            kept += 1;
            image_bytes += image;
        }
        ok
    });
    *entries = keep;
    dropped
}

/// ASCII-case-insensitive substring test without lowercasing the haystack
/// (a history holds up to 500 × 256 KB). `needle` is already lowercase.
fn contains_ci(hay: &str, needle: &str) -> bool {
    let n = needle.as_bytes();
    n.is_empty()
        || hay
            .as_bytes()
            .windows(n.len())
            .any(|w| w.eq_ignore_ascii_case(n))
}

/// The filter field and the type menu: text content, file paths/names and
/// the source app's name, any case.
pub fn matches(e: &Entry, query: &str, kind: Option<Kind>) -> bool {
    let q = query.trim().to_ascii_lowercase();
    kind.is_none_or(|k| e.kind == k)
        && (contains_ci(&e.text, &q) || e.source.as_ref().is_some_and(|s| contains_ci(&s.name, &q)))
}

/// What Return does: paste into the frontmost app needs the Accessibility
/// permission (to send ⌘V); without it the entry is only copied and the
/// panel says how to grant it.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum PastePlan {
    PasteIntoApp,
    CopyOnly,
}

pub fn paste_plan(accessibility_granted: bool) -> PastePlan {
    if accessibility_granted {
        PastePlan::PasteIntoApp
    } else {
        PastePlan::CopyOnly
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn text(t: &str, at: u64) -> Entry {
        Entry {
            id: content_id(text_kind(t), t.as_bytes()),
            kind: text_kind(t),
            text: t.into(),
            width: 0,
            height: 0,
            size: t.len() as u64,
            source: Some(Source {
                name: "Safari".into(),
                bundle_id: Some("com.apple.Safari".into()),
            }),
            first_ms: at,
            last_ms: at,
            count: 1,
            pinned: false,
        }
    }

    fn image(id: &str, size: u64, at: u64) -> Entry {
        Entry {
            id: id.into(),
            kind: Kind::Image,
            text: String::new(),
            width: 381,
            height: 60,
            size,
            ..text("", at)
        }
    }

    #[test]
    fn copying_the_same_content_again_bumps_it_to_the_top() {
        let mut h = Vec::new();
        assert!(record(&mut h, text("alpha", 1)));
        assert!(record(&mut h, text("beta", 2)));
        let mut again = text("alpha", 3);
        again.source = None;
        assert!(!record(&mut h, again));
        assert_eq!(h.len(), 2, "no duplicate");
        assert_eq!(h[0].text, "alpha");
        assert_eq!((h[0].count, h[0].first_ms, h[0].last_ms), (2, 1, 3));
        assert!(h[0].source.is_some(), "the first source stays");
    }

    #[test]
    fn ids_are_stable_and_kind_aware() {
        // Pinned value: the id is persisted, so the hash must never drift.
        assert_eq!(
            content_id(Kind::Text, b"alpha"),
            content_id(Kind::Text, b"alpha")
        );
        assert_ne!(
            content_id(Kind::Text, b"alpha"),
            content_id(Kind::File, b"alpha")
        );
        assert_eq!(content_id(Kind::Text, b""), "af63bd4c8601b7df");
    }

    #[test]
    fn retention_keeps_500_recent_unpinned_and_every_pinned() {
        let day = 24 * 60 * 60 * 1000;
        let now = 100 * day;
        let mut h: Vec<Entry> = (0..600u64)
            .map(|i| text(&format!("t{i}"), now - i))
            .collect();
        h[599].pinned = true; // the oldest one
        h.push(text("stale", now - 31 * day));
        let mut stale_pinned = text("stale pinned", now - 90 * day);
        stale_pinned.pinned = true;
        h.push(stale_pinned);
        let dropped = prune(&mut h, now);
        assert_eq!(h.iter().filter(|e| !e.pinned).count(), MAX_ENTRIES);
        assert!(
            h.iter().any(|e| e.text == "t599"),
            "pinned survives the count cap"
        );
        assert!(
            h.iter().any(|e| e.text == "stale pinned"),
            "pinned survives age"
        );
        assert!(!h.iter().any(|e| e.text == "stale"));
        assert_eq!(dropped.len(), 600 + 2 - h.len());
        assert_eq!(h[0].text, "t0", "order kept, newest first");
    }

    #[test]
    fn images_share_a_byte_budget_oldest_dropped_first() {
        let half = MAX_IMAGE_BYTES_TOTAL / 2 + 1;
        let mut h = vec![
            image("new", half, 3),
            image("mid", half, 2),
            image("old", 10, 1),
        ];
        let dropped = prune(&mut h, 3);
        assert_eq!(
            h.iter().map(|e| e.id.as_str()).collect::<Vec<_>>(),
            ["new", "old"]
        );
        assert_eq!(dropped[0].id, "mid");
    }

    #[test]
    fn concealed_and_password_manager_copies_are_skipped() {
        let t = |v: &[&str]| v.iter().map(|s| s.to_string()).collect::<Vec<_>>();
        assert!(skip(&t(&[
            "public.utf8-plain-text",
            "org.nspasteboard.ConcealedType"
        ])));
        assert!(skip(&t(&["org.nspasteboard.TransientType"])));
        assert!(skip(&t(&["org.nspasteboard.AutoGeneratedType"])));
        assert!(skip(&t(&[
            "com.agilebits.onepassword",
            "public.utf8-plain-text"
        ])));
        assert!(!skip(&t(&["public.utf8-plain-text", "public.rtf"])));
        assert!(!skip(&[]));
    }

    #[test]
    fn links_are_a_single_url() {
        assert_eq!(text_kind(" https://example.com/a?b=1 \n"), Kind::Link);
        assert_eq!(text_kind("http://x.dev"), Kind::Link);
        assert_eq!(text_kind("see https://example.com"), Kind::Text);
        assert_eq!(text_kind("ftp://x"), Kind::Text);
    }

    #[test]
    fn search_covers_text_file_names_and_source_with_a_type_filter() {
        let a = text("Deploy LOG line", 1);
        let mut f = text("/Users/me/Reports/Q3.pdf", 1);
        f.kind = Kind::File;
        assert!(matches(&a, "", None));
        assert!(matches(&a, "log", None));
        assert!(matches(&a, "  deploy ", Some(Kind::Text)));
        assert!(!matches(&a, "log", Some(Kind::Image)));
        assert!(matches(&f, "q3.PDF", Some(Kind::File)));
        assert!(matches(&a, "safari", None), "source app name");
        assert!(!matches(&a, "chrome", None));
    }

    #[test]
    fn return_pastes_only_with_accessibility_else_copies() {
        assert_eq!(paste_plan(true), PastePlan::PasteIntoApp);
        assert_eq!(paste_plan(false), PastePlan::CopyOnly);
    }
}
